// Part 3 — SensorData in a hand-written binary format.
//
// "Don't roll your own" is the rule. This is the one time you do, because
// writing a byte layout once is how padding and endianness stop being
// abstract — and because device manuals and protocol specifications
// describe their data exactly like this, as a table of bytes.
//
// The wire layout, version 1. All multi-byte numbers are LITTLE-ENDIAN.
//
//   offset  size  field
//   ------  ----  -----------------------------------------------------------
//        0     4  magic: the ASCII bytes 'A' 'I' 'S' '2'  (41 49 53 32)
//        4     1  version: 1
//        5     1  flags:  bit 0 = imu.is_valid
//                         bit 1 = accelerometer.is_valid
//                         bit 2 = temperature is present
//                         bits 3-7 must be zero
//        6     4  sequence           u32
//       10     8  timestamp_ms       i64 (two's complement)
//       18     1  N = length of sensor_id in bytes (0-255)
//       19     N  sensor_id          the characters, no terminator
//     19+N    24  imu roll, pitch, yaw                 3 x f64 (IEEE-754)
//     43+N    24  accelerometer x, y, z                3 x f64
//     67+N     8  temperature        f64 — ONLY if flags bit 2 is set
//
// So a reading is 67+N bytes without a temperature and 75+N with one. There
// is no padding anywhere, and nothing depends on the machine that wrote it.
//
// DO NOT EDIT this file — implement the functions in src/binary_format.cpp.

#ifndef AIS2203_BINARY_FORMAT_HPP
#define AIS2203_BINARY_FORMAT_HPP

#include "ais2203/parse_error.hpp"
#include "ais2203/sensor_data.hpp"

#include <cstdint>
#include <span>
#include <vector>

namespace ais2203 {

// Throws std::length_error if sensor_id is longer than 255 bytes (the layout
// has one byte for its length — silently truncating would be worse).
std::vector<std::uint8_t> encodeBinary(const SensorData& data);

// Throws ais2203::ParseError if the bytes are not exactly one valid version-1
// reading: too short, wrong magic, unknown version, reserved flag bits set,
// or bytes left over at the end. It must NEVER read outside `bytes`, whatever
// they contain — the sanitizer job in CI checks that.
SensorData decodeBinary(std::span<const std::uint8_t> bytes);

} // namespace ais2203

#endif // AIS2203_BINARY_FORMAT_HPP
